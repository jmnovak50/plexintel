-- MANUAL OPT-IN ONLY. This nested directory is intentionally outside the startup glob.
-- Apply with: psql -X -v ON_ERROR_STOP=1 --single-transaction -f this-file
SET LOCAL lock_timeout = '5s';
SET LOCAL search_path = pg_catalog, public, pg_temp;
SELECT pg_advisory_xact_lock(184725, 30);

CREATE TABLE IF NOT EXISTS public.seerr_discovery_runs (
    run_id uuid PRIMARY KEY,
    started_at timestamptz NOT NULL,
    completed_at timestamptz,
    status text NOT NULL CHECK (status IN ('running', 'success', 'partial', 'failed')),
    operation text NOT NULL CHECK (operation IN ('discover', 'enrich')),
    source_key text NOT NULL,
    parameters jsonb NOT NULL,
    pagination jsonb NOT NULL DEFAULT '[]',
    counts jsonb NOT NULL DEFAULT '{}',
    discovery_complete boolean NOT NULL DEFAULT false,
    enrichment_complete boolean NOT NULL DEFAULT false,
    errors jsonb NOT NULL DEFAULT '[]',
    warnings jsonb NOT NULL DEFAULT '[]',
    CHECK ((status = 'running') = (completed_at IS NULL)),
    CHECK (status <> 'success' OR (discovery_complete AND enrichment_complete))
);

CREATE TABLE IF NOT EXISTS public.seerr_discovered_movies (
    tmdb_id bigint PRIMARY KEY CHECK (tmdb_id > 0),
    title text,
    original_title text,
    synopsis text,
    original_language text,
    release_date date,
    discovery_release_date date,
    runtime integer CHECK (runtime > 0),
    genres jsonb,
    directors text[],
    cast_members jsonb,
    crew_members jsonb,
    production_countries jsonb,
    production_companies jsonb,
    popularity double precision,
    vote_count bigint,
    vote_average double precision,
    release_events jsonb,
    media_status integer,
    media_status_4k integer,
    media_state jsonb NOT NULL DEFAULT '{}',
    first_discovered_at timestamptz NOT NULL,
    first_discovery_run_id uuid NOT NULL REFERENCES public.seerr_discovery_runs(run_id),
    last_observed_at timestamptz NOT NULL,
    last_enriched_at timestamptz,
    last_enrichment_attempt_at timestamptz,
    metadata_updated_at timestamptz NOT NULL,
    enrichment_status text NOT NULL DEFAULT 'pending' CHECK (enrichment_status IN ('pending', 'success', 'failed')),
    enrichment_error text,
    metadata_source_key text,
    metadata_fingerprint text NOT NULL,
    field_states jsonb NOT NULL DEFAULT '{}',
    source_metadata jsonb NOT NULL DEFAULT '{}',
    CHECK (last_observed_at >= first_discovered_at),
    CHECK (genres IS NULL OR jsonb_typeof(genres) = 'array'),
    CHECK (cast_members IS NULL OR jsonb_typeof(cast_members) = 'array')
);

CREATE TABLE IF NOT EXISTS public.seerr_discovery_observations (
    observation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id uuid NOT NULL REFERENCES public.seerr_discovery_runs(run_id),
    tmdb_id bigint NOT NULL REFERENCES public.seerr_discovered_movies(tmdb_id),
    scope_key text NOT NULL,
    scope_name text NOT NULL,
    observation_kind text NOT NULL CHECK (observation_kind IN ('discovery', 'refresh')),
    query_parameters jsonb NOT NULL,
    observed_at timestamptz NOT NULL,
    discovery_metadata jsonb NOT NULL,
    detail_metadata jsonb,
    detail_observed_at timestamptz,
    enrichment_outcome text NOT NULL DEFAULT 'pending' CHECK (enrichment_outcome IN ('pending', 'success', 'cached', 'failed', 'deferred')),
    enrichment_error text,
    source_fingerprint text NOT NULL,
    prior_metadata_fingerprint text,
    metadata_fingerprint text NOT NULL,
    changed_fields text[] NOT NULL DEFAULT '{}',
    is_new boolean NOT NULL,
    UNIQUE (run_id, tmdb_id, scope_key)
);

CREATE INDEX IF NOT EXISTS seerr_discovery_runs_latest_idx ON public.seerr_discovery_runs(started_at DESC);
CREATE INDEX IF NOT EXISTS seerr_movies_first_seen_idx ON public.seerr_discovered_movies(first_discovered_at DESC);
CREATE INDEX IF NOT EXISTS seerr_movies_last_seen_idx ON public.seerr_discovered_movies(last_observed_at DESC);
CREATE INDEX IF NOT EXISTS seerr_movies_refresh_idx ON public.seerr_discovered_movies(enrichment_status, last_enriched_at);
CREATE INDEX IF NOT EXISTS seerr_movies_language_date_idx ON public.seerr_discovered_movies(original_language, release_date);
CREATE INDEX IF NOT EXISTS seerr_observations_movie_idx ON public.seerr_discovery_observations(tmdb_id, observed_at DESC);
CREATE INDEX IF NOT EXISTS seerr_observations_scope_idx ON public.seerr_discovery_observations(scope_key, run_id);

REVOKE ALL ON public.seerr_discovery_runs, public.seerr_discovered_movies, public.seerr_discovery_observations FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.seerr_discovery_observations_observation_id_seq FROM PUBLIC;
